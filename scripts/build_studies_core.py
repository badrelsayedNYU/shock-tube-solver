"""Extract the lab's existing 1D solver and add passive conservation diagnostics.

Run after changing the embedded ST solver: python scripts/build_studies_core.py
The cylinder app and its HTML are never modified by this generator.
"""
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
source = (ROOT / "docs/index.html").read_text()
core = re.search(r"const ST = \(\(\) => \{[\s\S]*?\n\}\)\(\);", source)[0]


def replace(old, new):
    global core
    assert core.count(old) == 1, f"Solver structure changed: {old}"
    core = core.replace(old, new)


replace("    const Us = [", """    const totals = () => U.map(row => row.reduce((a,b) => a+b, 0) * dx);
    const initialTotals = totals(), boundaryFlux = [0, 0, 0];
    const Us = [""")
replace("      for (let s = 0; s < stages.length; s++) {", """      const stepFlux = [0, 0, 0];
      for (let s = 0; s < stages.length; s++) {""")
replace("        operator(Us, L);", """        operator(Us, L);
        // Euler weight 1; SSP-RK2 weights 1/2, 1/2. Commit only accepted steps.
        for (let v = 0; v < 3; v++) stepFlux[v] += dt * (second ? 0.5 : 1) * (F[v][0] - F[v][N]);""")
replace("      t = tNew; steps++;", """      for (let v = 0; v < 3; v++) boundaryFlux[v] += stepFlux[v];
      t = tNew; steps++;""")
replace("    return { x, dx, N, t, steps, ms,", """    const finalTotals = totals();
    const conservation = { initial: initialTotals, final: finalTotals, boundaryFlux,
      residual: finalTotals.map((value,v) => value-initialTotals[v]-boundaryFlux[v]) };
    return { conservation, x, dx, N, t, steps, ms,""")
output = "// Generated by scripts/build_studies_core.py from the lab's ST solver.\n" + core + "\n"
target = ROOT / "docs/studies-core.js"
if "--check" in sys.argv:
    assert target.read_text() == output, "Regenerate studies-core.js after updating the lab solver"
else:
    target.write_text(output)
